package com.prosoft.webinar20.model

/**
 * Доменная модель заметки — то, что хранится ВНУТРИ приложения.
 *
 * Сознательно отделена от DTO (пакет dto), которые уходят наружу через API.
 * Это ключевой архитектурный приём: внутреннюю модель можно менять, не ломая
 * контракт API. В домашнем задании на месте этой модели будет JPA @Entity.
 */
data class Note(
    val id: Long,
    val title: String,
    val text: String,
)
